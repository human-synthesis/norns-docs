#!/usr/bin/env bun
/**
 * Generated reference pages. Runs before `dev` and `build` (see package.json).
 *
 * Today this copies the component reference that norns-ui generates from its
 * own type shims (`COMPONENTS.md`, produced by `bun run docs:components` in
 * the norns-ui repo and shipped in the npm package) into the content tree as
 * the norns-ui "Component reference" page. The output file is gitignored: the
 * installed package version is the source of truth.
 *
 * Later additions planned here: per-component pages, the norns CLI help
 * text, the norns-mcp tool list.
 */
import { createRequire } from 'node:module';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const require = createRequire(join(root, 'package.json'));

function componentsReference() {
	let pkgJson;
	try {
		pkgJson = require.resolve('@human-synthesis/norns-ui/package.json');
	} catch {
		console.warn('[gen-reference] @human-synthesis/norns-ui is not installed; skipping the component reference.');
		return;
	}
	const pkgDir = dirname(pkgJson);
	const { version } = JSON.parse(readFileSync(pkgJson, 'utf8'));
	const src = join(pkgDir, 'COMPONENTS.md');
	if (!existsSync(src)) {
		console.warn(`[gen-reference] ${src} not found (norns-ui ${version} predates COMPONENTS.md); skipping.`);
		return;
	}

	let md = readFileSync(src, 'utf8');
	// Drop the package-level H1 and the "generated" note; the page gets its
	// own title from frontmatter and its own provenance callout below.
	md = md.replace(/^# [^\n]*\n+/, '').replace(/^Generated by[^\n]*\n+/, '');

	const out = join(root, 'content', 'norns-ui', '30-reference', '10-components.md');
	mkdirSync(dirname(out), { recursive: true });
	writeFileSync(
		out,
		[
			'---',
			'title: Component reference',
			'description: Every component with its import path and prop types, generated from the norns-ui type shims.',
			'---',
			'',
			`> [!NOTE] Generated from \`src/types/*.d.ts\` in \`@human-synthesis/norns-ui\` ${version} by \`scripts/gen-reference.mjs\`. Do not edit this page by hand; fix the shim in norns-ui and re-run \`bun run docs:components\` there.`,
			'',
			md.trimEnd(),
			''
		].join('\n')
	);
	console.log(`[gen-reference] wrote ${out} (norns-ui ${version})`);
}

componentsReference();
